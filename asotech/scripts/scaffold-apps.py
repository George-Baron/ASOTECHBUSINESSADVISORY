"""One-off scaffold of the four Next.js apps (configs, root layout, auth pages). Idempotent: overwrites only scaffold files."""
import json, os
APPS = {
 "website":            dict(port=3000, title="ASOTECH Business Advisory", pub=True,  extra={}),
 "inventory-app":      dict(port=3001, title="ASOTECH Inventory", pub=False, extra={"read-excel-file": "^5.8.6"}),
 "client-portal":      dict(port=3002, title="ASOTECH Client Portal", pub=False, extra={}),
 "project-management": dict(port=3003, title="ASOTECH Project Management", pub=False, extra={}),
}
def w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(text)

for name, c in APPS.items():
    base = f"apps/{name}"
    pkg = {
      "name": f"@asotech/{name}", "version": "1.0.0", "private": True,
      "scripts": {"dev": f"next dev -p {c['port']}", "build": "next build", "start": f"next start -p {c['port']}", "typecheck": "tsc --noEmit", "lint": "next lint"},
      "dependencies": {
        "next": "^15.1.0", "react": "^19.0.0", "react-dom": "^19.0.0",
        "@asotech/ui": "*", "@asotech/utilities": "*", "@asotech/types": "*", "@asotech/validation": "*",
        "@asotech/configuration": "*", "@asotech/business-logic": "*", "@asotech/supabase": "*", **c["extra"],
      },
      "devDependencies": {"@types/node": "^22.0.0", "@types/react": "^19.0.0", "@types/react-dom": "^19.0.0",
                          "autoprefixer": "^10.4.20", "postcss": "^8.4.49", "tailwindcss": "^3.4.17", "typescript": "^5.6.0"},
    }
    w(f"{base}/package.json", json.dumps(pkg, indent=2) + "\n")
    w(f"{base}/next.config.mjs", """/** @type {import('next').NextConfig} */
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(self), microphone=(), geolocation=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
];
const nextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  transpilePackages: ["@asotech/ui", "@asotech/utilities", "@asotech/types", "@asotech/validation", "@asotech/configuration", "@asotech/business-logic", "@asotech/supabase"],
  async headers() { return [{ source: "/:path*", headers: securityHeaders }]; },
};
export default nextConfig;
""")
    w(f"{base}/tsconfig.json", json.dumps({
      "extends": "../../tsconfig.json",
      "compilerOptions": {"plugins": [{"name": "next"}], "incremental": True, "jsx": "preserve"},
      "include": ["next-env.d.ts", "**/*.ts", "**/*.tsx", ".next/types/**/*.ts"],
      "exclude": ["node_modules"]}, indent=2) + "\n")
    w(f"{base}/next-env.d.ts", '/// <reference types="next" />\n/// <reference types="next/image-types/global" />\n\n// NOTE: This file is regenerated by Next.js. Do not edit.\n')
    w(f"{base}/postcss.config.mjs", "export default { plugins: { tailwindcss: {}, autoprefixer: {} } };\n")
    w(f"{base}/tailwind.config.ts", """import type { Config } from "tailwindcss";
import preset from "../../packages/configuration/tailwind-preset";

const config: Config = {
  presets: [preset as Config],
  content: ["./app/**/*.{ts,tsx}", "./components/**/*.{ts,tsx}", "../../packages/ui/src/**/*.{ts,tsx}"],
};
export default config;
""")
    w(f"{base}/app/globals.css", """@tailwind base;
@tailwind components;
@tailwind utilities;

:root { color-scheme: light; }
html { scroll-behavior: smooth; }
body { @apply bg-cloud font-sans text-navy antialiased; }
:focus-visible { outline: 2px solid #F28C1E; outline-offset: 2px; }
@media (prefers-reduced-motion: reduce) { html { scroll-behavior: auto; } * { animation: none !important; transition: none !important; } }
@media print { .no-print { display: none !important; } body { background: #fff; } }
""")
    w(f"{base}/app/layout.tsx", f"""import type {{ Metadata, Viewport }} from "next";
import type {{ ReactNode }} from "react";
import "./globals.css";

export const metadata: Metadata = {{
  title: {{ default: "{c['title']}", template: "%s | ASOTECH" }},
  description: "ASOTECH Business Advisory. Control. Accuracy. Intelligence.",
  icons: {{ icon: "/favicon.svg" }},
{"  metadataBase: new URL(process.env.NEXT_PUBLIC_WEBSITE_URL ?? 'http://localhost:3000')," if c['pub'] else "  robots: { index: false, follow: false },"}
}};
export const viewport: Viewport = {{ width: "device-width", initialScale: 1, themeColor: "#0B2F4F" }};

export default function RootLayout({{ children }}: {{ children: ReactNode }}) {{
  return (
    <html lang="en-NG">
      <body>
        <a href="#main" className="sr-only focus:not-sr-only focus:absolute focus:left-2 focus:top-2 focus:z-50 focus:rounded focus:bg-white focus:px-3 focus:py-2 focus:font-semibold">Skip to content</a>
        {{children}}
      </body>
    </html>
  );
}}
""")
    w(f"{base}/public/favicon.svg", open("public/brand/favicon.svg").read())
    w(f"{base}/public/logo.svg", open("public/brand/logo.svg").read())
    w(f"{base}/public/icon.svg", open("public/brand/icon.svg").read())
    if not c["pub"]:
        w(f"{base}/middleware.ts", """import type { NextRequest } from "next/server";
import { updateSession } from "@asotech/supabase/middleware";

export async function middleware(request: NextRequest) {
  return updateSession(request, ["/login", "/register", "/forgot-password", "/reset-password", "/auth/", "/api/", "/forbidden"]);
}
export const config = { matcher: ["/((?!_next/static|_next/image|favicon.svg|logo.svg|icon.svg).*)"] };
""")
        w(f"{base}/app/auth/callback/route.ts", 'import type { NextRequest } from "next/server";\nimport { handleAuthCallback } from "@asotech/supabase/callback";\n\nexport const GET = (request: NextRequest) => handleAuthCallback(request);\n')
        w(f"{base}/app/forbidden/page.tsx", """import { AuthCard } from "@asotech/ui";
import { signOut } from "@asotech/supabase/auth";

export const metadata = { title: "Access denied" };
export default function Forbidden() {
  return (
    <AuthCard title="You do not have access" subtitle="Your account is signed in but is not permitted to use this area.">
      <form action={signOut}><button className="w-full rounded-lg bg-navy px-4 py-2.5 text-sm font-bold text-white hover:bg-navy-700">Sign out</button></form>
    </AuthCard>
  );
}
""")
        sub = {"inventory-app": "Sign in to manage your inventory", "client-portal": "Sign in to see your projects, reports and deliverables", "project-management": "ASOTECH staff sign in"}[name]
        reg_ok = name != "project-management"
        w(f"{base}/app/login/page.tsx", f"""import Link from "next/link";
import {{ AuthCard, AuthForm }} from "@asotech/ui";
import {{ signIn, safeNext }} from "@asotech/supabase/auth";

export const metadata = {{ title: "Sign in" }};
export default async function LoginPage({{ searchParams }}: {{ searchParams: Promise<{{ error?: string; notice?: string; next?: string }}> }}) {{
  const sp = await searchParams;
  return (
    <AuthCard
      title="Welcome back" subtitle="{sub}"
      footer={{<>{"<>New here? <Link className=\"font-semibold text-navy underline\" href=\"/register\">Create an account</Link> · </>" if reg_ok else ""}<Link className="font-semibold text-navy underline" href="/forgot-password">Forgot password?</Link></>}}
    >
      <AuthForm mode="login" action={{signIn}} error={{sp.error}} notice={{sp.notice}} next={{await safeNext(sp.next)}} />
    </AuthCard>
  );
}}
""")
        w(f"{base}/app/forgot-password/page.tsx", """import Link from "next/link";
import { AuthCard, AuthForm } from "@asotech/ui";
import { requestPasswordReset } from "@asotech/supabase/auth";

export const metadata = { title: "Reset password" };
export default function ForgotPage() {
  return (
    <AuthCard title="Reset your password" subtitle="Enter your email and we will send a reset link." footer={<Link className="font-semibold text-navy underline" href="/login">Back to sign in</Link>}>
      <AuthForm mode="forgot" action={requestPasswordReset} />
    </AuthCard>
  );
}
""")
        w(f"{base}/app/reset-password/page.tsx", """import { AuthCard } from "@asotech/ui";
import { updatePassword } from "@asotech/supabase/auth";

export const metadata = { title: "Choose a new password" };
export default async function ResetPage({ searchParams }: { searchParams: Promise<{ error?: string }> }) {
  const sp = await searchParams;
  return (
    <AuthCard title="Choose a new password">
      <form action={updatePassword} className="space-y-4">
        {sp.error && <p role="alert" className="rounded-lg border border-red-200 bg-red-50 px-3 py-2 text-sm text-bad">{sp.error}</p>}
        <div>
          <label htmlFor="password" className="mb-1 block text-sm font-semibold text-navy">New password</label>
          <input id="password" name="password" type="password" required minLength={10} autoComplete="new-password" className="w-full rounded-lg border border-navy-200 px-3 py-2.5 text-sm focus:border-navy focus:outline-none focus:ring-2 focus:ring-brand-orange/60" />
        </div>
        <button className="w-full rounded-lg bg-brand-orange px-4 py-2.5 text-sm font-bold text-navy hover:bg-[#f59a38]">Update password</button>
      </form>
    </AuthCard>
  );
}
""")
        if reg_ok:
            w(f"{base}/app/register/page.tsx", """import Link from "next/link";
import { AuthCard, AuthForm } from "@asotech/ui";
import { signUp } from "@asotech/supabase/auth";

export const metadata = { title: "Create account" };
export default async function RegisterPage({ searchParams }: { searchParams: Promise<{ error?: string }> }) {
  const sp = await searchParams;
  return (
    <AuthCard title="Create your account" footer={<>Already registered? <Link className="font-semibold text-navy underline" href="/login">Sign in</Link></>}>
      <AuthForm mode="register" action={signUp} error={sp.error} />
    </AuthCard>
  );
}
""")
        else:
            w(f"{base}/app/register/page.tsx", """import { redirect } from "next/navigation";
// Staff accounts are created by an administrator in Supabase; there is no public registration here.
export default function RegisterPage() { redirect("/login"); }
""")
print("scaffolded", list(APPS))
